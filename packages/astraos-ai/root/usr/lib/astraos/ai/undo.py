"""Undo and snapshots: a tested way back before privileged work.

WHY THIS EXISTS
    Astra Guard records what happened; this module makes a reversible copy of
    the things that are about to change, so a privileged action can be undone.
    The first implementation is file-tree snapshots (copy-based), which works on
    ext4 today; a Btrfs snapshot default is a later, evaluated change
    (docs/ROADMAP.md, Stage 3).

    The interface is deliberately small and pure-Python so it can be tested on
    any host: snapshot(paths) -> id, rollback(id) -> restored paths, list
    snapshots. Nothing here touches the system or requires root.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import stat
import time
import uuid
from pathlib import Path
from typing import Iterable

SNAPSHOT_ROOT = None  # resolved lazily


def _root() -> Path:
    global SNAPSHOT_ROOT
    if SNAPSHOT_ROOT is not None:
        return Path(SNAPSHOT_ROOT)
    import os

    base = os.environ.get("ASTRAOS_UNDO_DIR") or os.environ.get("ASTRAOS_SNAPSHOT_DIR")
    if base:
        root = Path(base)
    else:
        xdg = os.environ.get("XDG_STATE_HOME")
        if xdg:
            root = Path(xdg) / "astraos" / "undo"
        else:
            root = Path.home() / ".local" / "state" / "astraos" / "undo"
    root.mkdir(parents=True, exist_ok=True)
    return root


def set_root(path) -> None:
    """Override the snapshot directory (used by tests)."""
    global SNAPSHOT_ROOT
    SNAPSHOT_ROOT = str(path)
    Path(path).mkdir(parents=True, exist_ok=True)


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _safe_name(path: Path) -> str:
    """A collision-free file name for a captured path.

    Replacing separators alone is not enough: /a/b and /a_b map to the same
    name, and the second copy would silently overwrite the first inside the
    snapshot. A short digest of the exact path keeps them apart.
    """
    text = str(path)
    readable = text.replace(":", "_").replace("\\", "_").replace("/", "_").lstrip("_")
    digest = hashlib.sha256(text.encode("utf-8", "replace")).hexdigest()[:10]
    return f"{readable[:120]}-{digest}"


class UndoManager:
    def __init__(self, root: Path | None = None):
        self.root = Path(root) if root is not None else _root()

    def _snapshot_dir(self, snapshot_id: str) -> Path:
        """The directory of one snapshot, refusing an id that is a path.

        Snapshot ids are generated by this class, but rollback ids also arrive
        from command lines and stored JSON. An id containing a separator or
        ".." would let the caller name any directory on the machine, so it is
        rejected rather than resolved.
        """
        text = str(snapshot_id or "")
        if not text or "/" in text or "\\" in text or text in (".", "..") or ":" in text:
            raise ValueError(f"not a snapshot id: {snapshot_id!r}")
        return self.root / text

    def snapshot(self, paths: Iterable[str | Path], label: str = "") -> str:
        """Copy the given paths into a new snapshot. Returns the snapshot id."""
        sid = uuid.uuid4().hex[:12]
        sdir = self._snapshot_dir(sid)
        sdir.mkdir(parents=True, exist_ok=True)
        manifest = {
            "id": sid,
            "created": _now(),
            "created_ns": time.time_ns(),
            "label": label,
            "entries": [],
        }
        for raw in paths or []:
            src = Path(raw)
            entry = {"path": str(src), "existed": False}
            if not src.exists() and not src.is_symlink():
                manifest["entries"].append(entry)
                continue
            dest = sdir / _safe_name(src)
            try:
                mode = src.lstat().st_mode
                if stat.S_ISLNK(mode):
                    dest.symlink_to(src.readlink())
                    entry["backup"] = str(dest)
                    entry["kind"] = "symlink"
                elif src.is_dir():
                    shutil.copytree(src, dest, symlinks=True, dirs_exist_ok=True)
                    entry["backup"] = str(dest)
                    entry["kind"] = "dir"
                elif src.is_file():
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(src, dest)
                    entry["backup"] = str(dest)
                    entry["kind"] = "file"
                else:
                    # A FIFO, socket or device node has no contents to copy.
                    # Recording it as uncaptured is honest; copying it can hang.
                    # existed stays True so rollback reports the missing backup
                    # instead of deleting a path it never captured.
                    entry["existed"] = True
                    entry["kind"] = "special"
                    entry["error"] = "not captured: not a regular file or directory"
                    manifest["entries"].append(entry)
                    continue
            except OSError as exc:
                entry["existed"] = True
                entry["kind"] = "error"
                entry["error"] = str(exc)
                manifest["entries"].append(entry)
                continue
            entry["existed"] = True
            manifest["entries"].append(entry)
        (sdir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        return sid

    def list_snapshots(self) -> list[dict]:
        out = []
        if not self.root.exists():
            return out
        for child in self.root.iterdir():
            manifest_path = child / "manifest.json"
            if manifest_path.is_file():
                try:
                    out.append(json.loads(manifest_path.read_text(encoding="utf-8")))
                except (OSError, ValueError):
                    continue
        # Oldest first, so "undo the most recent" is the last entry and a
        # listing reads in the order the snapshots were taken. Directory names
        # are random hex, which is why this cannot be a name sort.
        out.sort(key=lambda entry: (
            int(entry.get("created_ns") or 0),
            str(entry.get("created") or ""),
            str(entry.get("id") or ""),
        ))
        return out

    def rollback(self, snapshot_id: str) -> dict:
        """Restore the paths captured in a snapshot. Returns a report."""
        try:
            sdir = self._snapshot_dir(snapshot_id)
        except ValueError as exc:
            return {"ok": False, "snapshot": snapshot_id, "restored": [], "errors": [str(exc)]}
        manifest_path = sdir / "manifest.json"
        if not manifest_path.is_file():
            return {"ok": False, "error": f"unknown snapshot {snapshot_id}"}
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        restored = []
        errors = []
        for entry in manifest.get("entries", []):
            target = Path(entry["path"])
            if not entry.get("existed"):
                # Path did not exist before: remove it if present now.
                if target.exists() or target.is_symlink():
                    try:
                        if target.is_dir() and not target.is_symlink():
                            shutil.rmtree(target)
                        else:
                            target.unlink()
                        restored.append(str(target))
                    except OSError as exc:
                        errors.append(f"{target}: {exc}")
                else:
                    restored.append(str(target))
                continue
            backup = Path(entry["backup"]) if entry.get("backup") else None
            if backup is None or not (backup.exists() or backup.is_symlink()):
                errors.append(f"{target}: backup missing")
                continue
            try:
                if target.exists() or target.is_symlink():
                    if target.is_dir() and not target.is_symlink():
                        shutil.rmtree(target)
                    else:
                        target.unlink()
                target.parent.mkdir(parents=True, exist_ok=True)
                if backup.is_symlink():
                    target.symlink_to(backup.readlink())
                elif backup.is_dir():
                    shutil.copytree(backup, target, symlinks=True, dirs_exist_ok=True)
                else:
                    shutil.copy2(backup, target)
                restored.append(str(target))
            except OSError as exc:
                errors.append(f"{target}: {exc}")
        return {"ok": not errors, "snapshot": snapshot_id, "restored": restored, "errors": errors}

    def delete(self, snapshot_id: str) -> bool:
        try:
            sdir = self._snapshot_dir(snapshot_id)
        except ValueError:
            return False
        if sdir.exists():
            shutil.rmtree(sdir, ignore_errors=True)
            return True
        return False


# Module-level convenience functions
_manager = None


def _default_manager() -> UndoManager:
    global _manager
    if _manager is None:
        _manager = UndoManager()
    return _manager


def snapshot(paths, label="", root=None):
    mgr = UndoManager(root) if root is not None else _default_manager()
    return mgr.snapshot(paths, label=label)


def create_snapshot(paths, label="", root=None):
    return snapshot(paths, label=label, root=root)


def rollback(snapshot_id, root=None):
    mgr = UndoManager(root) if root is not None else _default_manager()
    return mgr.rollback(snapshot_id)


def restore(snapshot_id, root=None):
    return rollback(snapshot_id, root=root)


def undo(snapshot_id=None, root=None):
    if snapshot_id is None:
        snaps = list_snapshots(root=root)
        if not snaps:
            return {"ok": False, "error": "no snapshots to undo"}
        snapshot_id = snaps[-1]["id"]
    return rollback(snapshot_id, root=root)


def list_snapshots(root=None):
    mgr = UndoManager(root) if root is not None else _default_manager()
    return mgr.list_snapshots()


def delete_snapshot(snapshot_id, root=None):
    mgr = UndoManager(root) if root is not None else _default_manager()
    return mgr.delete(snapshot_id)


# Aliases
create = snapshot
make_snapshot = snapshot
take_snapshot = snapshot
perform_rollback = rollback
revert = rollback


